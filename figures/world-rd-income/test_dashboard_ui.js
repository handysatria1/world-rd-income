'use strict';
const assert=require('node:assert/strict');
const ui=require('./dashboard_ui.js');
assert.equal(ui.readConfig(''),null);
assert.equal(ui.readConfig('?config=%7Bbroken'),null);
assert.equal(ui.readConfig('?config='+encodeURIComponent(JSON.stringify({v:2,ids:[]}))),null);
assert.equal(ui.readConfig('?config='+encodeURIComponent(JSON.stringify({v:1,ids:['<script>']}))),null);
const value={v:1,ids:['USA','ES-PV'],controls:{'shared-year':'2022'}};
assert.deepEqual(ui.readConfig('?config='+encodeURIComponent(JSON.stringify(value))),value);
const select=(id,value,values)=>({id,value,tagName:'SELECT',type:'select-one',options:values.map(value=>({value}))});
const metric=select('metric','nominal',['nominal','ppp','pppConstant']);
const year=select('year','2022',['2022','2023']);
const strict={id:'strict',type:'checkbox',checked:false,tagName:'INPUT'};
const title={id:'title-input',type:'text',value:'Original',tagName:'INPUT'};
const doc={querySelectorAll:()=>[metric,year,strict,title]};
assert.deepEqual(ui.capture(doc),{metric:'nominal',strict:false,'title-input':'Original'});
ui.apply(doc,{metric:'pppConstant',year:'2023',strict:true,'title-input':'My comparison'});
assert.equal(metric.value,'pppConstant');assert.equal(year.value,'2022');assert.equal(strict.checked,true);assert.equal(title.value,'My comparison');
ui.apply(doc,{metric:'invented-series',strict:'false','title-input':'x'.repeat(301)});
assert.equal(metric.value,'pppConstant');assert.equal(strict.checked,true);assert.equal(title.value,'My comparison');
assert.deepEqual(ui.apply(doc,[]),[]);
console.log('Dashboard UI: versioned share links, malformed input, control allowlists, price-basis restoration and value validation passed.');
